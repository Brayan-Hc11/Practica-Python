
# Los operadores aritmeticos:
# son aquellos que manipulan datos númericos, tanto números enteros, así como números decimales también conocidos como reales.


# Suma(+)

num_uno = 1
num_dos = 2

suma = num_uno + num_dos 

print('El resultado de la suma es: ' + str(suma))

# Resta(-)

num_uno = 2
num_dos = 1

resta = num_uno - num_dos

print('El resultado de la resta es: ' + str(resta))


# Multiplicación(*)

num_uno = 5
num_dos = 4

multiplicacion = num_uno * num_dos

print('El resultado de la multiplicación es: ' + str(multiplicacion))

# Exponente(**)

num_uno = 5
num_dos = 4

exponente = num_uno ** num_dos

print('El resultado de la potencia es : ' + str(exponente))

# División(/)

num_uno = 10
num_dos = 2

division = num_uno / num_dos

print('El resultado de la divición es: ' + str(division))

# Módulo(%)

num_uno = 20
num_dos = 6

modulo = num_uno % num_dos 

print('El resultado del modulo o resto es de: ' + str(modulo))

# División entera(//)

num_uno = 10
num_dos = 2

division_entera = num_uno // num_dos

print('El resultado de la división entera es: ' + str(division_entera))

